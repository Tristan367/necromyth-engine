// A 5x7 pixel font, authored for this project.
//
// Written out rather than loaded, and drawn rather than borrowed, for two
// reasons. The first is that a font file is an asset to ship, install and find
// at runtime, and a HUD that cannot draw text because a path was wrong is worse
// than one that cannot be restyled. The second is licensing: the obvious
// shortcut is a console bitmap font off the system, and those are GPL, which is
// not a decision a renderer gets to make on a project's behalf.
//
// 5x7 is the classic readable minimum -- it is what an LCD character module
// uses -- and it is the size at which glyphs are DESIGNED rather than sampled.
// That is the whole point of a pixel font: rasterising an outline face at eight
// pixels gives mush, because at that size the shapes have to be chosen, and
// every one of these was.
//
