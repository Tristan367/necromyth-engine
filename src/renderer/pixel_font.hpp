// The bitmap for a character, or the blank of a space for anything outside the
// set -- a HUD asked to print a byte it has no glyph for should leave a gap,
// not an artefact and not a crash.
[[nodiscard]] inline constexpr auto glyph_of(char c) -> const Glyph & {
  if (c < k_first_glyph || c > k_last_glyph)
    return k_glyphs[0];
  return k_glyphs[static_cast<std::size_t>(c - k_first_glyph)];
}

[[nodiscard]] inline constexpr auto lit(const Glyph &glyph, int x, int y) -> bool {
  if (x < 0 || x >= k_glyph_width || y < 0 || y >= k_glyph_height)
    return false;
  return (glyph[static_cast<std::size_t>(y)] & (1U << static_cast<unsigned>(x))) != 0U;
}

